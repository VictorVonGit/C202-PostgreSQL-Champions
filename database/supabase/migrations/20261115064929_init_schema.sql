-- 1. Independent tables (Parents: no FK)
create table if not exists public.library_user (
  user_id integer generated by default as identity not null,
  first_name text not null,
  last_name text not null,
  email text not null,
  constraint library_user_pkey primary key (user_id),
  constraint library_user_email_key unique (email)
) TABLESPACE pg_default;

create table if not exists public.publisher (
  publisher_id integer generated by default as identity not null,
  publisher_name text not null,
  address text null,
  contact_email text not null,
  constraint publisher_pkey primary key (publisher_id)
) TABLESPACE pg_default;

-- 2. First-level child tables (dependent on library_user or publisher)
create table if not exists public.member (
  user_id integer not null,
  phone text not null,
  standing text not null,
  constraint member_pkey primary key (user_id),
  constraint member_user_id_fkey foreign key (user_id) references public.library_user (user_id) on update cascade on delete cascade
) TABLESPACE pg_default;

create table if not exists public.book (
  book_id integer generated by default as identity not null,
  title character varying(255) not null,
  isbn character varying(20) not null,
  publication_year integer not null,
  publisher_id integer not null,
  constraint book_pkey primary key (book_id),
  constraint book_isbn_key unique (isbn),
  constraint book_publisher_id_fkey foreign key (publisher_id) references public.publisher (publisher_id) on update cascade on delete cascade
) TABLESPACE pg_default;

-- 3. Second-level child tables (dependent on member and/or book)
create table if not exists public.author (
  author_id integer generated by default as identity not null,
  author_name text not null,
  bio text null,
  user_id integer not null,
  constraint author_pkey primary key (author_id, user_id),
  constraint author_user_id_fkey foreign key (user_id) references public.member (user_id) on update cascade on delete cascade
) TABLESPACE pg_default;

create table if not exists public.loan (
  loan_id integer generated by default as identity not null,
  user_id integer not null,
  book_id integer not null,
  loan_date date not null,
  loan_expiration_date date not null,
  return_date date null,
  constraint loan_pkey primary key (loan_id),
  constraint loan_book_id_fkey foreign key (book_id) references public.book (book_id) on update cascade on delete cascade,
  constraint loan_user_id_fkey foreign key (user_id) references public.member (user_id) on update cascade on delete cascade
) TABLESPACE pg_default;

create table if not exists public.reservation (
  reservation_id integer generated by default as identity not null,
  user_id integer not null,
  book_id integer not null,
  reservation_date date not null,
  reservation_expiration_date date not null,
  constraint reservation_pkey primary key (reservation_id),
  constraint reservation_book_id_fkey foreign key (book_id) references public.book (book_id) on update cascade on delete cascade,
  constraint reservation_user_id_fkey foreign key (user_id) references public.member (user_id) on update cascade on delete cascade
) TABLESPACE pg_default;
